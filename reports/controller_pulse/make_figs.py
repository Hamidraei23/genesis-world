def aligned_params(v, A=15.0, T_rev_hold=None):
    """linear_vel_test settings with the reversal on a publish tick and a matching reverse hold."""
    t_up = 0.02 * np.ceil(v / 4.0 / 0.02)
    params = {"target_vel": v, "accel_up": v / t_up, "accel_down": A}
    if T_rev_hold is not None:
        params["reverse_hold"] = T_rev_hold
    return params


def slip_vs_latency(params, tilt, mu, lat_ms, Tp=TP):
    prof, t, v = profile_arrays(params, t_end=1.2)
    arm = controller_chain(t, v)["arm"]
    out = []
    for L in lat_ms:
        tr = prof.pulse_send_time() + L * 1e-3
        _, w, d = simulate_slip(t, arm, tr, tr + Tp, tilt, mu=mu)
        out.append((d[-1] * 1e3, w[-1], d.max() * 1e3))
    return np.array(out), prof, t, arm


