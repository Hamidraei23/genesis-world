def equivalent_release(t, hv, ov, F, r0, g_a):
    j = r0
    while j < r0 + 80 and not np.all(F[j:j + 5] < 1e-3):
        j += 1
    line = ov[j] - g_a * (t - t[j])
    win = np.arange(r0 - 5, j + 1)
    return win[np.argmin(np.abs(line[win] - hv[win]))]


def regrip_index(F, r0):
    j = r0 + 100
    while F[j] < 1.0:
        j += 1
    return j


