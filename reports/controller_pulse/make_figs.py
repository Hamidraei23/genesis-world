def sweep_slip(path):
    d = np.load(path)
    v, L, o = d["vpeak"], d["length"], d["offset"]
    out = {}
    for tilt in d["tilts"]:
        k = f"t{int(tilt)}"
        rel, trig = d[k + "_rel_z"], d[k + "_trigger"]
        idx = np.arange(len(v))
        before = rel[idx, trig - 1]
        after = rel[idx, np.minimum(trig + L + 3, rel.shape[1] - 1)]
        out[int(tilt)] = (after - before) * 1e3
    return v, L, o, out


