def design_table():
    rows = []
    cases = [
        ("current defaults", {}, TP),
        ("reversal on a tick", aligned_params(0.45, T_rev_hold=0.1), TP),
        ("matched speed", aligned_params(0.65, T_rev_hold=0.15), TP),
        ("matched pulse", aligned_params(0.45, T_rev_hold=0.1), 0.085),
    ]
    lat = np.arange(0, 81, 1.0)
    for name, params, Tp in cases:
        res, prof, t, arm = slip_vs_latency(params, TILT, MU, lat, Tp=Tp)
        best = int(np.argmax(res[:, 0]))
        lo, hi = np.clip(best - 10, 0, len(lat) - 1), np.clip(best + 10, 0, len(lat) - 1)
        mus = [slip_vs_latency(params, TILT, m, lat[[best]], Tp=Tp)[0][0, 0] for m in (0.6, 0.9)]
        free_res = slip_vs_latency(params, TILT, 0.0, lat, Tp=Tp)[0]
        free = free_res[:, 0].max()
        high, low = prof.extremes()
        acc = np.gradient(arm, t[1] - t[0])
        rows.append({
            "name": name, "v": prof.target, "a_up": prof.accel_up, "Tp": Tp * 1e3,
            "lat": lat[best], "slip": res[best, 0], "w": res[best, 1],
            "pm10": (res[lo, 0], res[hi, 0]), "mu": tuple(mus), "free": free,
            "arm_peak": arm.max(), "arm_min": arm.min(), "arm_acc": np.abs(acc).max(),
            "high": high * 1e3, "low": low * 1e3,
        })
    (HERE / "design_table.json").write_text(json.dumps(rows, indent=1, default=float))
    lines = []
    for r in rows:
        lines.append(
            f"{r['name']} & {r['v']:.2f} & {r['Tp']:.0f} & {r['lat']:.0f} & {r['slip']:.1f} & "
            f"{r['pm10'][0]:.1f}\\,/\\,{r['pm10'][1]:.1f} & {min(r['mu']):.1f}--{max(r['mu']):.1f} & "
            f"{r['w']:+.2f} & {r['free']:.1f} & {r['arm_peak']:.2f}\\,/\\,{r['arm_min']:.2f} & "
            f"{r['high']:+.0f}\\,/\\,{r['low']:+.0f} \\\\"
        )
    (HERE / "design_table.tex").write_text("\n".join(lines) + "\n")
    print("wrote design_table.tex")


