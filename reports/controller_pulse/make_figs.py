FRICTION_GRID = np.round(np.arange(0.0, 1.0001, 0.05), 2)
FRICTION_TABLE = [0.0, 0.3, 0.5, 0.75, 1.0]


def matched_through_chain(arms, vs, tilt, mu):
    """Peak speed where w crosses zero at re-grip, and the slip there, through the full chain."""
    W, D = [], []
    for t, arm, tr in arms:
        _, w, d = simulate_slip(t, arm, tr, tr + TP, tilt, mu=mu)
        W.append(w[-1])
        D.append(d[-1] * 1e3)
    W, D = np.array(W), np.array(D)
    k = np.where(np.diff(np.sign(W)) > 0)[0]
    if not len(k):
        return np.nan, np.nan
    j = k[0]
    vm = vs[j] - W[j] * (vs[j + 1] - vs[j]) / (W[j + 1] - W[j])
    return float(vm), float(np.interp(vm, vs, D))


